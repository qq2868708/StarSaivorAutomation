def make_event(item: dict) -> dict:
    cell = item["source_cell"]
    slug = re.sub(r"[^a-z0-9]+", "_", cell.lower()).strip("_")
    sheet_prefix = {
        "支援卡事件": "support_card",
        "跑马基础事件": "base",
        "阿加农地区": "arcanum",
        "海滩地区": "beach",
        "温泉地区": "hot_spring",
        "重置老板娘": "reset",
        "讨伐事件": "hunt",
        "气候事件": "climate",
    }.get(item.get("sheet", "支援卡事件"), "document")
    event = {
        "id": f"{sheet_prefix}_{slug}",
        "event_name": item["event_name"],
        "title_aliases": [item["event_name"]],
        "category": item["category"],
        "source_sheet": item.get("sheet", "支援卡事件"),
        "source_cell": cell,
        "source_document": SOURCE,
        "source_document_aliases": ALIASES,
        "document_verified": True,
        "status": "confirmed",
        "recommended_option": 1,
        "card": item["card"],
        "options": [],
    }
    for index, effect in enumerate(item["effects"], start=1):
        quantified = quantify_effect_text(effect)
        option = {
            "index": index,
            "keyword": "",
            "alias": [],
            "effect_text": effect,
            "quantified": quantified,
        }
        option["score_attack"] = option_score(option, "attack")
        option["score_survival"] = option_score(option, "survival")
        event["options"].append(option)
    return event


def _merge_unique(existing, generated):
    """按原顺序合并字符串列表，供重复导入时保留人工 OCR 校正。"""
    result = []
    for value in list(existing or []) + list(generated or []):
        if value and value not in result:
            result.append(value)
    return result


